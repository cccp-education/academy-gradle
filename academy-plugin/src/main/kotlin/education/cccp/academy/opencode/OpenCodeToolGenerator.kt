package education.cccp.academy.opencode

/**
 * One generated opencode custom-tool file (ACADEMY-16).
 *
 * opencode discovers custom tools in `.opencode/tools/`; the **filename**
 * becomes the tool name and each exported symbol becomes
 * `<filename>_<export>` (verified against the opencode custom-tools docs,
 * 2026-11-05). A single file is generated so the installer can stage it with
 * one heredoc and the Linux/Windows parity stays structural.
 *
 * @property relativePath path relative to the workspace root
 * @property content rendered TypeScript content
 */
data class OpenCodeToolFile(
    val relativePath: String,
    val content: String,
) {
    init {
        require(relativePath.isNotBlank()) { "relativePath must not be blank" }
        require(content.isNotBlank()) { "content must not be blank" }
    }
}

/**
 * Renders the public boroughs as opencode custom tools (ACADEMY-16).
 *
 * This is the executable counterpart of [OpenCodeCatalog]: the catalog is the
 * single source of truth (plugin id, role, verified tasks, version), and the
 * generator turns every **enabled** entry (non-blank version) into a TypeScript
 * `tool()` wrapper that runs the corresponding Gradle task in the learner
 * workspace.
 *
 * The wrapper is deliberately thin: it does not reimplement any borough logic,
 * it only invokes the published Gradle task. The agent keeps the reasoning;
 * the borough keeps the business logic.
 */
object OpenCodeToolGenerator {
    /** Directory opencode scans for project-level custom tools. */
    const val TOOLS_DIRECTORY: String = ".opencode/tools"

    /** The single generated file (multiple exports = multiple tools). */
    const val FILE_NAME: String = "cccp.ts"

    /**
     * Renders the tool file for every enabled plugin of [plugins].
     *
     * @throws IllegalArgumentException when no plugin is enabled (a tool file
     *   with no tool would silently expose nothing).
     */
    fun renderAll(plugins: List<OpenCodePlugin>): OpenCodeToolFile {
        val enabled = plugins.filter { it.version.isNotBlank() }
        require(enabled.isNotEmpty()) { "at least one public plugin must be enabled (non-blank version)" }

        val content =
            buildString {
                appendLine("// Generated by education.cccp.academy (ACADEMY-16). Do not edit.")
                appendLine("// Public boroughs exposed as opencode custom tools.")
                appendLine("import { tool } from \"@opencode-ai/plugin\"")
                enabled.forEach { plugin ->
                    appendLine()
                    append(renderExport(plugin))
                }
            }
        return OpenCodeToolFile(relativePath = "$TOOLS_DIRECTORY/$FILE_NAME", content = content)
    }

    private fun renderExport(plugin: OpenCodePlugin): String {
        val exportName = exportName(plugin.id)
        val tasks = plugin.tasks.joinToString(", ") { "\"$it\"" }
        return buildString {
            appendLine("export const $exportName = tool({")
            appendLine("  description: \"${plugin.role.replace("\"", "'")}\",")
            appendLine("  args: {")
            appendLine("    task: tool.schema.enum([$tasks]).describe(\"Gradle task to run\"),")
            appendLine("    args: tool.schema.string().optional().describe(\"Extra Gradle arguments\"),")
            appendLine("  },")
            appendLine("  async execute({ task, args }, context) {")
            appendLine("    const extraArgs = args ? args.split(\" \").filter(Boolean) : []")
            appendLine("    const shell = Bun.\$.cwd(context.directory)")
            appendLine("    return (await shell`gradle \${task} \${extraArgs.join(\" \")}`.text()).trim()")
            appendLine("  },")
            appendLine("})")
        }
    }

    /**
     * The exported symbol for a plugin id — the last segment, normalized to a
     * safe TypeScript identifier (`education.cccp.slider` → `slider`).
     */
    fun exportName(pluginId: String): String =
        pluginId
            .substringAfterLast('.')
            .replace('-', '_')
            .replace('.', '_')
}
